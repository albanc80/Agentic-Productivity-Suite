"""Deliverable export: Markdown and standalone HTML.

The HTML uses a neutral theme. A private theme (``theme.css`` in
``theme_dir``) can restyle exports at runtime without putting any brand
assets in the repository. Raw HTML in model output is never rendered.
"""

from __future__ import annotations

import html
from pathlib import Path

from markdown_it import MarkdownIt

_MD = MarkdownIt("commonmark", {"html": False, "linkify": False, "typographer": False}).enable("table")

NEUTRAL_CSS = """
:root{--bg:#fff;--fg:#17212b;--muted:#5b6b78;--line:#d8dee4;--accent:#1f6f78;--soft:#f3f6f8}
@media (prefers-color-scheme:dark){:root{--bg:#10171d;--fg:#e3e9ee;--muted:#9aabb8;--line:#2a3742;--accent:#5bbac4;--soft:#17222b}}
*{box-sizing:border-box}body{margin:0;background:var(--bg);color:var(--fg);font:16px/1.6 "IBM Plex Sans","Segoe UI",Roboto,Arial,sans-serif}
main{max-width:860px;margin:0 auto;padding:40px 20px 80px}
h1,h2,h3{line-height:1.2;font-family:"Archivo","Segoe UI",Arial,sans-serif}h1{font-size:2rem}h2{margin-top:2rem;border-top:1px solid var(--line);padding-top:1rem}
blockquote{margin:1rem 0;padding:.6rem 1rem;background:var(--soft);border-left:3px solid var(--accent)}
table{border-collapse:collapse;width:100%;font-size:.92rem;display:block;overflow-x:auto}th,td{border:1px solid var(--line);padding:6px 10px;text-align:left;vertical-align:top}
th{background:var(--soft)}code{font-family:"IBM Plex Mono",Consolas,monospace;font-size:.9em}pre{background:var(--soft);padding:12px;overflow-x:auto}
a{color:var(--accent)}footer{margin-top:3rem;color:var(--muted);font-size:.85rem}
"""


def to_html(markdown: str, title: str, theme_dir: Path | None = None) -> str:
    body = _MD.render(markdown or "")
    css = NEUTRAL_CSS
    if theme_dir and (theme_dir / "theme.css").exists():
        css += "\n" + (theme_dir / "theme.css").read_text(encoding="utf-8")
    return (f"<!doctype html><html lang=\"en\"><head><meta charset=\"utf-8\">"
            f"<meta name=\"viewport\" content=\"width=device-width,initial-scale=1\">"
            f"<title>{html.escape(title)}</title><style>{css}</style></head><body><main>{body}"
            f"<footer>Generated by Agentic Productivity Suite. Draft for human review; not approved unless an approval is recorded above.</footer>"
            f"</main></body></html>")
